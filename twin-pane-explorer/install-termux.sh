#!/data/data/com.termux/files/usr/bin/bash
# =============================================================================
#  Twin-Pane Explorer - installer for Termux
#  Usage:  bash install-termux.sh
# =============================================================================
set -e

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PREFIX_BIN="${PREFIX:-/data/data/com.termux/files/usr}/bin"
LAUNCHER="$PREFIX_BIN/twinpane"

say()  { printf '\033[1;36m::\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31mXX\033[0m %s\n' "$*" >&2; exit 1; }

say "Twin-Pane Explorer installer"
say "source folder: $APP_DIR"

# ---------------------------------------------------------------------------
# 1. Python
# ---------------------------------------------------------------------------
if ! command -v python3 >/dev/null 2>&1; then
    warn "python3 not found - installing it with pkg (needs internet)"
    pkg install -y python || die "could not install python. Run: pkg install python"
fi
say "python: $(python3 --version 2>&1)"

if ! python3 -c "import curses" >/dev/null 2>&1; then
    warn "python curses module is missing - installing python-curses"
    pkg install -y python-curses || die "python-curses install failed"
fi

# ---------------------------------------------------------------------------
# 2. Shared storage (Android 7+ needs this once)
# ---------------------------------------------------------------------------
if [ ! -d "$HOME/storage" ] && [ ! -d /sdcard ]; then
    warn "Termux has no storage access yet. Run 'termux-setup-storage' and"
    warn "tap Allow, then re-run this installer."
fi

# ---------------------------------------------------------------------------
# 3. launcher in \$PREFIX/bin
# ---------------------------------------------------------------------------
mkdir -p "$PREFIX_BIN"
cat > "$LAUNCHER" <<LAUNCH_EOF
#!/data/data/com.termux/files/usr/bin/bash
# Twin-Pane Explorer launcher (generated by install-termux.sh)
export TWINPANE_HOME="$APP_DIR"
export PYTHONPATH="$APP_DIR\${PYTHONPATH:+:\$PYTHONPATH}"
exec python3 -m twinpane "\$@"
LAUNCH_EOF
chmod 755 "$LAUNCHER"
say "launcher installed: $LAUNCHER"

# ---------------------------------------------------------------------------
# 4. shell aliases / convenience
# ---------------------------------------------------------------------------
BASHRC="$HOME/.bashrc"
if ! grep -q "alias twin=" "$BASHRC" 2>/dev/null; then
    {
        echo ""
        echo "# Twin-Pane Explorer shortcuts"
        echo "alias twin='twinpane'"
        echo "alias explorer='twinpane -l ~ -r /sdcard'"
    } >> "$BASHRC"
    say "added 'twin' and 'explorer' aliases to ~/.bashrc"
else
    say "aliases already present in ~/.bashrc"
fi

# ---------------------------------------------------------------------------
# 5. extra keys (optional, big quality-of-life win on a phone keyboard)
# ---------------------------------------------------------------------------
TERMUX_PROPS="$HOME/.termux/termux.properties"
if [ -f "$APP_DIR/docs/termux.properties" ]; then
    mkdir -p "$HOME/.termux"
    if ! grep -q "Twin-Pane Explorer" "$TERMUX_PROPS" 2>/dev/null; then
        printf '\n# --- Twin-Pane Explorer extra keys (added by install-termux.sh) ---\n' \
            >> "$TERMUX_PROPS"
        sed -n '/^extra-keys/,/^]/p' "$APP_DIR/docs/termux.properties" >> "$TERMUX_PROPS"
        command -v termux-reload-settings >/dev/null 2>&1 && termux-reload-settings || true
        say "added an extra-keys row to ~/.termux/termux.properties (ESC TAB / - HOME UP ...)"
    else
        say "extra keys already configured"
    fi
fi

# ---------------------------------------------------------------------------
# 6. self-check
# ---------------------------------------------------------------------------
say "running self-test (file operations only) ..."
if PYTHONPATH="$APP_DIR" python3 - "$APP_DIR" <<'TEST_EOF'
import os, shutil, sys, tempfile
sys.path.insert(0, sys.argv[1])
from twinpane import fsops

work = tempfile.mkdtemp(prefix="twinpane-selftest-")
try:
    src = os.path.join(work, "termux")
    dst = os.path.join(work, "sdcard")
    os.makedirs(os.path.join(src, "sub"))
    os.makedirs(dst)
    with open(os.path.join(src, "sub", "hello.txt"), "w") as fh:
        fh.write("salam")
    result = fsops.Transfer().run_copy([os.path.join(src, "sub")], dst)
    assert not result.errors, result.errors
    copied = os.path.join(dst, "sub", "hello.txt")
    assert os.path.exists(copied), "copy did not produce %s" % copied
    moved = fsops.Transfer().run_move([copied], src)
    assert not moved.errors, moved.errors
    assert not os.path.exists(copied)
    assert os.path.exists(os.path.join(src, "hello.txt"))

    # zip + unzip round-trip (pure stdlib, must work on-device)
    archive = os.path.join(work, "test.zip")
    repacked = fsops.create_archive([os.path.join(src, "sub")], archive)
    assert not repacked.errors, repacked.errors
    out = os.path.join(work, "unzipped")
    extracted = fsops.extract_archive(archive, out)
    assert not extracted.errors, extracted.errors
    assert os.path.exists(os.path.join(out, "sub", "hello.txt"))
finally:
    shutil.rmtree(work, ignore_errors=True)
print("self-test: copy + move + zip + unzip OK")
TEST_EOF
then
    say "self-test passed"
else
    die "self-test failed - please report the output above"
fi

echo
say "Done. Start it with:"
echo "     twin            # or: twinpane"
echo "     explorer        # Termux home <-> /sdcard"
echo
echo "Inside the app press F1 for the full key list."
echo "If /sdcard shows 'Permission denied':  termux-setup-storage"
